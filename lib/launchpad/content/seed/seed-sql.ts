import { canonicalJson, launchpadContentHash } from "@/lib/launchpad/content/content-hash";
import { checkLaunchpadVenturePayload } from "@/lib/launchpad/content/check-payload";
import type { LaunchpadVenturePayload } from "@/lib/launchpad/content/types";

/** Postgres dollar-quote tag; the payload must not contain it. */
const TAG = "$lp_seed$";

/**
 * One version insert and one current-pointer upsert.
 * Columns match launchpad_venture_versions (venture_id, content_hash, payload;
 * id and created_at default) and launchpad_venture_current (venture_id,
 * version_id; updated_at defaults, and is set again only when the pointer moves).
 */
function publishStatements(payload: LaunchpadVenturePayload): string {
  const check = checkLaunchpadVenturePayload(payload);
  if (!check.ok) throw new Error(`Seed payload is invalid: ${check.reason}`);
  const json = canonicalJson(payload);
  if (json.includes(TAG)) throw new Error("Seed payload contains the quote tag.");
  const hash = launchpadContentHash(payload);
  const venture = payload.ventureId; // checked against ^[a-z0-9][a-z0-9-]*$
  return `insert into public.launchpad_venture_versions (venture_id, content_hash, payload)
values (
  '${venture}',
  '${hash}',
  ${TAG}${json}${TAG}::jsonb
)
on conflict (venture_id, content_hash) do nothing;

insert into public.launchpad_venture_current (venture_id, version_id)
select venture_id, id
from public.launchpad_venture_versions
where venture_id = '${venture}' and content_hash = '${hash}'
on conflict (venture_id) do update
  set version_id = excluded.version_id,
      updated_at = now()
  where public.launchpad_venture_current.version_id is distinct from excluded.version_id;`;
}

/**
 * Idempotent SQL that stores `payload` as a version and makes it current.
 * Re-running it inserts nothing new and leaves the pointer on the same row.
 * Used to write supabase/seeds/launchpad_test_venture_seed.sql; a test keeps
 * that file in step with the bundled seed.
 */
export function launchpadSeedSql(payload: LaunchpadVenturePayload): string {
  const venture = payload.ventureId;
  return `-- GENERATED by tools/launchpad-seed-sql.ts from
-- lib/launchpad/content/seed/launchpad-test-venture-seed.ts. Do not edit by hand.
--
-- TEST content for the Launchpad test venture "${venture}": Level 1 (Vision and
-- Goals: "Define the business" with 3 bronzes, "Set your goals" with 1 bronze)
-- plus the placeholder floors 2 to 6 of the r4 building (16 silvers in total).
-- Stores it in launchpad_venture_versions and points launchpad_venture_current
-- at it (published). Idempotent: safe to run more than once.
-- Needs 20261104090000_launchpad_venture_content.sql applied first.
-- Run with the service role (SQL editor). Not part of the migrations folder.

begin;

${publishStatements(payload)}

commit;
`;
}

/**
 * Publish SQL for the ventures the loader asks for. Today that is dog-walking
 * only: it is the one live venture id, and the only id whose bundled seed has
 * all seven built levels. LAUNCHPAD_DB_VENTURES stays empty, so the app still
 * reads the seed until that list and the flag change.
 */
export function launchpadPublishV4Sql(payloads: readonly LaunchpadVenturePayload[]): string {
  if (payloads.length === 0) throw new Error("Publish SQL needs at least one venture.");
  const slugs = payloads.map((payload) => payload.ventureId);
  const body = payloads.map((payload) => publishStatements(payload)).join("\n\n");
  return `-- GENERATED by tools/launchpad-seed-sql.ts from the current bundled seed.
-- Do not edit by hand.
--
-- Schema 4. Slugs: ${slugs.join(", ")}.
-- Each slug gets one launchpad_venture_versions row (the full seven-level
-- payload, including Level Up content and surface copy) and one
-- launchpad_venture_current pointer. Idempotent: a second run inserts nothing
-- and leaves the pointer on the same row.
-- INSERT/UPSERT only. No DDL, deletes, or grants.
-- Run with the service role (SQL editor). Not a migration.

begin;

${body}

commit;
`;
}
